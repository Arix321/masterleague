export interface MarketSeedPlayer {
  name: string;
  position: Position;
  overall: number;
  marketValue: number;
  expectedWage: number;
  region: string;
  currentClub: string;
  age: number;
}

const ovrFromValue = (eur: number, age: number) => {
  let o: number;
  if (eur >= 30_000_000) o = 85;
  else if (eur >= 18_000_000) o = 83;
  else if (eur >= 12_000_000) o = 81;
  else if (eur >= 7_000_000) o = 78;
  else if (eur >= 4_000_000) o = 76;
  else if (eur >= 2_000_000) o = 74;
  else if (eur >= 1_000_000) o = 72;
  else if (eur >= 500_000) o = 70;
  else if (eur >= 200_000) o = 67;
  else o = 64;
  if (age <= 20) o -= 2;
  else if (age >= 35) o -= 2;
  return Math.max(58, Math.min(91, o));
};
const wageFromValue = (eur: number, o: number) => {
  const base = Math.max(20_000, Math.round(eur * 0.012));
  const floor = Math.max(20_000, (o - 65) * 8000);
  return Math.max(base, floor);
};

const m = (
  name: string,
  position: Position,
  marketValue: number,
  currentClub: string,
  age = 25,
  region = "Brasil",
): MarketSeedPlayer => {
  const o = ovrFromValue(marketValue, age);
  return {
    name, position, overall: o, marketValue,
    expectedWage: wageFromValue(marketValue, o),
    region, currentClub, age,
  };
};

